window.onload = function () {
  //<editor-fold desc="Changeable Configuration Block">

  // Listen for authentication tokens from parent page
  let authToken = null;
  let isLoggedIn = false;

  window.addEventListener("message", (event) => {
    console.log("Swagger received message:", event.data);
    if (event.data.type === "AUTH_TOKEN") {
      authToken = event.data.token;
      isLoggedIn = event.data.isLogged;
      console.log("Swagger received auth token:", {
        hasToken: !!authToken,
        isLoggedIn: isLoggedIn,
        tokenLength: authToken ? authToken.length : 0,
      });
    }
  });

  // Moves the definition picker out of the dark topbar and under the API title.
  //
  // `InfoUrl` is the last child of <hgroup class="main">, so wrapping it lands
  // the picker inside that hgroup, directly beneath <h2 class="title">. Doing it
  // as a wrapComponents plugin rather than by relocating the DOM node keeps it
  // inside React's tree, so it survives the re-render that switching definitions
  // triggers. The topbar's own copy is hidden in index.css.
  const DefinitionPickerPlugin = () => ({
    wrapComponents: {
      InfoUrl: (Original, system) => (props) => {
        const React = system.React;
        const original = React.createElement(Original, props);

        const configs = system.getConfigs();
        const urls = configs.urls || [];
        if (urls.length < 2) return original;

        // The spec URL in state is absolute while the configured ones are
        // relative, so compare resolved forms to find the current entry.
        const resolve = (value) => {
          try {
            return new URL(value, window.location.href).href;
          } catch (error) {
            return value;
          }
        };
        const current = resolve(system.specSelectors.url());
        const selected = urls.find((entry) => resolve(entry.url) === current) || urls[0];

        const onChange = (event) => {
          const url = event.target.value;
          // Same order the stock topbar uses: drop credentials belonging to the
          // outgoing definition, then point the spec at the new one.
          if (!configs.persistAuthorization) {
            system.authActions.restoreAuthorization({ authorized: {} });
          }
          system.specActions.updateUrl(url);
          system.specActions.download(url);
        };

        return React.createElement(
          React.Fragment,
          null,
          original,
          React.createElement(
            "label",
            { className: "definition-select" },
            React.createElement("span", null, "API definition"),
            React.createElement(
              "select",
              { value: selected.url, onChange: onChange, "aria-label": "Select API definition" },
              urls.map((entry) => React.createElement("option", { key: entry.url, value: entry.url }, entry.name)),
            ),
          ),
        );
      },
    },
  });

  // One definition per API version.
  //
  // Deliberately not a single document with two `servers` entries: `servers`
  // means "the same API at several base URLs", so picking v2 there would keep
  // all of v1's operations on screen even though v2 implements two of them.
  // Both documents are generated by `npm run schema:generate`.
  window.ui = SwaggerUIBundle({
    urls: [
      { url: "/schema/openapi.json", name: "Rolnopol API (deprecated)" },
      { url: "/schema/openapi.v1.json", name: "Rolnopol API v1 (stable)" },
      { url: "/schema/openapi.v2.json", name: "Rolnopol API v2 (development)" },
    ],
    "urls.primaryName": "Rolnopol API (deprecated)",
    dom_id: "#swagger-ui",
    deepLinking: true,
    presets: [SwaggerUIBundle.presets.apis, SwaggerUIStandalonePreset],
    plugins: [SwaggerUIBundle.plugins.DownloadUrl, DefinitionPickerPlugin],
    layout: "StandaloneLayout",
    requestInterceptor: (request) => {
      // Add authentication token if available
      if (authToken && isLoggedIn) {
        request.headers.token = authToken;
      }
      return request;
    },
    responseInterceptor: (response) => {
      // Handle authentication errors gracefully
      if (response.status === 401 || response.status === 403) {
        // Send message to parent page about auth error
        if (window.parent && window.parent !== window) {
          window.parent.postMessage(
            {
              type: "AUTH_ERROR",
              message: "Authentication required for this endpoint",
            },
            "*",
          );
        }
      }
      return response;
    },
    onComplete: () => {
      console.log("Swagger UI loaded successfully");
    },
    onFailure: (data) => {
      console.error("Swagger UI failed to load:", data);
    },
  });

  //</editor-fold>
};
